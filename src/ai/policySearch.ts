export function normalizeArabic(value: string): string {
  return value
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function getSearchTerms(label: string): string[] {
  return [label, ...(documentKeywordMap[label] ?? [])];
}

export function extractSnippet(
  sourceText: string,
  searchTerms: string[],
  radius = 130,
): { matchedText: string; excerpt: string } | null {
  for (const term of searchTerms) {
    const index = sourceText.indexOf(term);
    if (index >= 0) {
      const start = Math.max(0, index - radius);
      const end = Math.min(sourceText.length, index + term.length + radius);
      return {
        matchedText: term,
        excerpt: sourceText.slice(start, end).replace(/\s+/g, " ").trim(),
      };
    }
  }

  const normalizedSource = normalizeArabic(sourceText);
  for (const term of searchTerms) {
    const normalizedTerm = normalizeArabic(term);
    if (!normalizedTerm) {
      continue;
    }
    const index = normalizedSource.indexOf(normalizedTerm);
    if (index >= 0) {
      const start = Math.max(0, index - radius);
      const end = Math.min(
        normalizedSource.length,
        index + normalizedTerm.length + radius,
      );
      return {
        matchedText: term,
        excerpt: normalizedSource.slice(start, end).trim(),
      };
    }
  }

  return null;
}
